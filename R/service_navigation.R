#' Service navigation
#'
#' @description
#' Service navigation component consistent with the
#' [GDS service navigation](https://design-system.service.gov.uk/components/service-navigation/). # nolint
#'
#' **Note:** This component uses a hardcoded element ID
#' for the navigation list and mobile menu toggle. Using
#' multiple `service_navigation()` instances on the same
#' page will cause ID conflicts and the mobile menu toggle
#' may not work correctly.
#'
#' The first in-app link is marked as the current page when the app loads,
#' matching the first tab panel Shiny shows by default. If your app starts on
#' a different page, call [update_service_navigation()] when the session
#' starts.
#'
#' On screens narrower than GOV.UK's tablet breakpoint (641px), the links are
#' collapsed behind a "Menu" button, as in the GOV.UK Design System. Choosing
#' an in-app link from the open menu closes it and moves keyboard focus to the
#' new page's `<h1>` (or `<main>` if it has none), as a page load would on a
#' GOV.UK service, rather than leaving focus on the hidden link.
#'
#' Put `service_navigation()` in your app's top-level UI and wire it up from
#' the top-level server function. It is not designed to be used inside a
#' Shiny module: an inputID wrapped in `ns()` is cleaned up like any other
#' (so `NS("mod", "summary")` becomes `mod_summary`), and no longer matches
#' the module's namespaced input.
#'
#' @param links A character vector of link text for the service navigation.
#' Each link's inputID is generated by lowercasing the text and replacing every
#' non-alphanumeric character with an underscore, e.g. "Overview page" becomes
#' `overview_page`. To choose the inputIDs yourself, supply a named vector
#' where names are the link text and values are the inputIDs, e.g.
#' `c("Overview page" = "overview")`. Supplied inputIDs are cleaned up in the
#' same way, so `"Page-Two"` becomes `page_two`. Every link must end up with
#' a unique inputID.
#'
#' A link can also go to an ordinary URL instead of a page in the app. Supply
#' it as a named value starting with `https://`, `http://`, `mailto:`, `/`,
#' `./`, `../`, `?` or `#`, e.g.
#' `c("Summary" = "summary", "Guidance" = "https://www.gov.uk/guidance")`.
#' These are plain links: they open in the same tab, as GOV.UK service
#' navigation links do, are never marked as the current page, and are ignored
#' by [update_service_navigation()] and [service_navigation_server()].
#' @param service_name An optional character string
#' containing the service name to be displayed in the
#' navigation bar
#' @param service_url An optional URL for the service name to link to,
#' usually the service's start page. If `NULL` (the default), the service name
#' is shown as text rather than a link, as in the GOV.UK Design System.
#' @param auto_page_title Logical. When `TRUE` (the default),
#' the browser tab title is updated to match the active nav
#' link whenever the user navigates — both by clicking a
#' link and via `update_service_navigation()`. Set to `FALSE`
#' to opt out and manage the page title yourself. Keeping
#' the title in sync with the visible page is a GOV.UK
#' Design System recommendation for accessibility.
#' @param page_title_suffix Optional character string
#' appended to the page title in the format
#' `"<link text> | <suffix>"` — typically the service name.
#' Only used when `auto_page_title = TRUE`. For finer
#' control (e.g. when a page heading differs from its nav
#' link label), call [update_page_title()] from your server
#' code.
#' @inheritParams width_arg
#'
#' @returns Shiny tag object
#' @family Govstyle navigation
#' @export
#'
#' @examples
#' ui <- shinyGovstyle::gov_page(
#'   shinyGovstyle::header("Title", "Secondary heading"),
#'   shinyGovstyle::service_navigation(
#'      c("Summary data", "Detailed stats 1", "User guide")
#'   ),
#'   bslib::navset_hidden(
#'      id = "main_panels",
#'      bslib::nav_panel(
#'        "summary_data",
#'        shiny::tags$h2("Summary data")
#'      ),
#'      bslib::nav_panel(
#'        "detailed_stats_1",
#'        shiny::tags$h2("Detailed stats 1")
#'      ),
#'      bslib::nav_panel(
#'        "user_guide",
#'        shiny::tags$h2("User guide")
#'      )
#'    ),
#'    shinyGovstyle::footer(full = TRUE)
#' )
#'
#' # A linked service name, and a link to a page outside the app
#' shinyGovstyle::service_navigation(
#'   c(
#'     "Summary data" = "summary_data",
#'     "Methodology" = "https://www.gov.uk/government/statistics"
#'   ),
#'   service_name = "School statistics",
#'   service_url = "/"
#' )
#'
#' server <- function(input, output, session) {
#'   observeEvent(
#'     input$summary_data,
#'     bslib::nav_select("main_panels", "summary_data")
#'   )
#'   observeEvent(
#'     input$detailed_stats_1,
#'     bslib::nav_select("main_panels", "detailed_stats_1")
#'   )
#'   observeEvent(
#'     input$user_guide,
#'     bslib::nav_select("main_panels", "user_guide")
#'   )
#' }
#'
#' if (interactive()) shiny::shinyApp(ui = ui, server = server)
service_navigation <- function(
  links,
  service_name = NULL,
  auto_page_title = TRUE,
  page_title_suffix = NULL,
  width = "standard",
  service_url = NULL
) {
  wc <- gov_width_container(width, is_default = missing(width))

  valid_url <- is.character(service_url) &&
    length(service_url) == 1 &&
    !is.na(service_url) &&
    nzchar(service_url)
  if (!is.null(service_url) && !valid_url) {
    stop("`service_url` must be a single, non-empty string.", call. = FALSE)
  }

  nav_links <- service_nav_ids(links)
  # The first in-app link starts as the current page, matching the first tab
  # panel Shiny shows. URL links are never the current page.
  first_app_link <- match(TRUE, is.na(nav_links$href))
  active <- seq_along(nav_links$id) == first_app_link
  navigation <- shiny::tags$section(
    `aria-label` = "Service information",
    class = "govuk-service-navigation",
    `data-module` = "govuk-service-navigation",
    `data-auto-page-title` = if (isTRUE(auto_page_title)) "true",
    `data-page-title-suffix` = if (
      isTRUE(auto_page_title) &&
        !is.null(page_title_suffix) &&
        nzchar(page_title_suffix)
    ) {
      page_title_suffix
    },
    shiny::tags$div(
      class = wc$class,
      style = wc$style,
      shiny::tags$div(
        class = "govuk-service-navigation__container",
        if (!is.null(service_name)) {
          # As in GOV.UK, the service name is only a link when it has
          # somewhere to go, rather than a placeholder href = "#"
          shiny::tags$span(
            class = "govuk-service-navigation__service-name",
            if (is.null(service_url)) {
              shiny::tags$span(
                class = "govuk-service-navigation__text",
                service_name
              )
            } else {
              shiny::tags$a(
                href = service_url,
                class = "govuk-service-navigation__link",
                service_name
              )
            }
          )
        },
        shiny::tags$nav(
          `aria-label` = "Menu",
          class = "govuk-service-navigation__wrapper",
          shiny::tags$button(
            type = "button",
            class = paste(
              "govuk-service-navigation__toggle",
              "govuk-js-service-navigation-toggle"
            ),
            `aria-controls` = "navigation",
            hidden = TRUE,
            "Menu"
          ),
          shiny::tags$ul(
            class = "govuk-service-navigation__list",
            id = "navigation",
            mapply(
              service_nav_link,
              nav_links$id,
              nav_links$label,
              active,
              nav_links$href,
              SIMPLIFY = FALSE,
              USE.NAMES = FALSE
            )
          )
        )
      )
    )
  )
  attachDependency(navigation, "service_navigation") # nolint
}


#' Update the active item in a service navigation component
#'
#' @description
#' Sends a message to the browser to change the active link in the service
#' navigation bar.
#'
#' **When you need this function:** when you change the tab from the server,
#' for example from a next button, and the tabset is not wired up with
#' [service_navigation_server()]. You also need it to keep a link active on a
#' panel that is not in `link_to_panel`, such as a sub-page.
#'
#' **When you don't need this function:** when the user clicks a nav link, or
#' when [service_navigation_server()] wires up the tabset. Both update the
#' active link for you.
#'
#' An `inputId` that matches no nav link clears the active link, e.g.
#' `update_service_navigation(session, "accessibility_statement")` for a page
#' that is not in the navigation.
#'
#' `inputId` is cleaned up the same way as in [service_navigation()], so
#' `"Page-Two"` and `"page_two"` both work.
#'
#' @param session The Shiny session object
#' @inheritParams id_arg
#'
#' @returns NULL, called for side effects
#' @family Govstyle navigation
#' @export
#'
#' @examples
#' # Works the same with shiny::tabsetPanel() + shiny::updateTabsetPanel().
#' ui <- shinyGovstyle::gov_page(
#'   shinyGovstyle::service_navigation(c("Page one", "Page two")),
#'   bslib::navset_hidden(
#'     id = "tabs",
#'     bslib::nav_panel("page_one", shiny::actionButton("next_btn", "Next")),
#'     bslib::nav_panel("page_two", "Page two content")
#'   )
#' )
#'
#' server <- function(input, output, session) {
#'   # Nav link clicked — JS handles the active state, just switch the panel.
#'   shiny::observeEvent(input$page_two, {
#'     bslib::nav_select("tabs", "page_two")
#'   })
#'
#'   # Programmatic navigation — the nav link is not clicked, so call
#'   # update_service_navigation() explicitly.
#'   shiny::observeEvent(input$next_btn, {
#'     bslib::nav_select("tabs", "page_two")
#'     shinyGovstyle::update_service_navigation(session, "page_two")
#'   })
#' }
#'
#' if (interactive()) shiny::shinyApp(ui = ui, server = server)
update_service_navigation <- function(
  session,
  inputId # nolint: object_name_linter.
) {
  session$sendCustomMessage(
    "update_service_navigation",
    clean_nav_id(inputId)
  )
}


#' Auto-wire service navigation links to tabset panels
#'
#' @description
#' Sets up one observer per nav link that switches the corresponding tab
#' panel when the link is clicked. Eliminates the per-link
#' `observeEvent()` boilerplate that multi-page apps would otherwise need.
#'
#' Call once in your server function, after [service_navigation()] has been
#' added to the UI. The active nav highlight and (when
#' `auto_page_title = TRUE`) the browser tab title are already handled
#' client-side, so no additional wiring is needed.
#'
#' It also follows the tabset. When a panel in `link_to_panel` is selected
#' from the server, for example with `shiny::updateTabsetPanel()`, its link
#' becomes active and the page title updates. A title set with
#' [update_page_title()] in the same observer as the tab change, or in an
#' observer of the tabset input, is kept; one set earlier is not. If several
#' links share a panel, the first is used unless one is already active.
#'
#' When a panel that is not in `link_to_panel` is selected, such as a footer
#' page, the active link is cleared so screen readers don't announce the
#' previous page as current. Set its title with [update_page_title()].
#'
#' Calling [update_service_navigation()] in the same observer as the tab
#' change overrides both, for example to keep a parent link active on a
#' sub-page.
#'
#' @param session The Shiny session object
#' @param tabset_id The `id` of the `shiny::tabsetPanel()` or
#'   `bslib::navset_hidden()` to switch
#' @param link_to_panel A character vector mapping nav link inputIds to
#'   tab panel values. Pass a **named** vector when inputIds differ from
#'   panel values (names = inputIds, values = panel values). Pass an
#'   **unnamed** vector as shorthand for the 1:1 case — each element is
#'   used as both the nav inputId and the panel value. InputIds are cleaned
#'   up the same way as in [service_navigation()], so `"Page-Two"` and
#'   `"page_two"` both refer to the same link. Panel values are used exactly
#'   as given.
#'
#' @returns NULL, called for side effects
#' @family Govstyle navigation
#' @export
#'
#' @examples
#' ui <- shinyGovstyle::gov_page(
#'   shinyGovstyle::service_navigation(
#'     c(Summary = "sn_summary", Detail = "sn_detail")
#'   ),
#'   bslib::navset_hidden(
#'     id = "tabs",
#'     bslib::nav_panel("summary", "Summary content"),
#'     bslib::nav_panel("detailed_data", "Detail content")
#'   )
#' )
#'
#' server <- function(input, output, session) {
#'   # Nav inputIds differ from panel values
#'   shinyGovstyle::service_navigation_server(
#'     session,
#'     tabset_id = "tabs",
#'     link_to_panel = c(
#'       sn_summary = "summary",
#'       sn_detail = "detailed_data"
#'     )
#'   )
#'
#'   # Or, when inputIds match panel values exactly:
#'   # shinyGovstyle::service_navigation_server(
#'   #   session,
#'   #   tabset_id = "tabs",
#'   #   link_to_panel = c("summary", "detailed_data")
#'   # )
#' }
#'
#' if (interactive()) shiny::shinyApp(ui = ui, server = server)
service_navigation_server <- function(
  session,
  tabset_id, # nolint: object_name_linter.
  link_to_panel
) {
  if (is.null(link_to_panel) || length(link_to_panel) == 0) {
    stop("link_to_panel must be a non-empty character vector")
  }
  stopifnot(is.character(link_to_panel))
  if (is.null(names(link_to_panel))) {
    names(link_to_panel) <- link_to_panel
  } else {
    blanks <- names(link_to_panel) == ""
    names(link_to_panel)[blanks] <- link_to_panel[blanks]
  }
  # Only the inputIds are cleaned; panel values must match the tab panels
  # exactly as given.
  names(link_to_panel) <- clean_nav_id(names(link_to_panel))

  input <- session$input
  lapply(seq_along(link_to_panel), function(i) {
    input_id <- names(link_to_panel)[i]
    panel <- link_to_panel[[i]]
    shiny::observeEvent(
      input[[input_id]],
      shiny::updateTabsetPanel(session, tabset_id, selected = panel),
      ignoreInit = TRUE
    )
  })

  # Keep the nav in step with tab changes made from the server
  shiny::observeEvent(
    input[[tabset_id]],
    {
      links <- names(link_to_panel)[link_to_panel == input[[tabset_id]]]
      # Sent even when empty, so the browser clears the nav. as.list() keeps
      # one link as a JSON array. The tabset id lets the browser match the
      # sync to an update_service_navigation() call made with the tab change.
      session$sendCustomMessage(
        "sync_service_navigation",
        list(tabset = session$ns(tabset_id), links = as.list(links))
      )
    },
    ignoreInit = TRUE
  )
  invisible(NULL)
}


# Internal helper: the one rule for turning a nav link id into its inputID.
# Shared by service_navigation() and the server helpers so that the same id
# string always refers to the same link, whichever function it is passed to.
clean_nav_id <- function(id) {
  tolower(gsub("[^a-zA-Z0-9]", "_", id))
}

# Internal helper: TRUE for nav link values that are URLs rather than
# inputIDs. inputIDs are always cleaned to letters, numbers and underscores,
# so a value starting with a scheme, a path or a fragment can never be one.
is_nav_url <- function(x) {
  grepl("^(https?://|mailto:|/|\\./|\\.\\./|\\?|#)", x, ignore.case = TRUE)
}

# Internal helper: resolves the link text, inputID and URL for each nav link.
# Named elements supply their own inputID (or a URL) as the value; unnamed
# elements use the link text. Either way the inputID is lowercased with
# non-alphanumerics replaced by underscores, so it is always a safe,
# predictable Shiny input. URL links have no inputID (NA) and an href.
service_nav_ids <- function(links) {
  if (is.null(links) || length(links) == 0) {
    stop("links must be a non-empty character vector", call. = FALSE)
  }
  if (!is.character(links) || anyNA(links) || !all(nzchar(links))) {
    stop(
      "links must be a character vector of non-empty strings",
      call. = FALSE
    )
  }

  link_text <- names(links)
  if (is.null(link_text)) {
    link_text <- rep("", length(links))
  }
  supplied_id <- !is.na(link_text) & nzchar(link_text)

  label <- ifelse(supplied_id, link_text, links)
  url <- is_nav_url(links)

  if (any(url & !supplied_id)) {
    stop(
      "Service navigation links to a URL need link text. Supply them in a ",
      "named vector, e.g. c(\"Guidance\" = \"",
      links[url & !supplied_id][[1]],
      "\").",
      call. = FALSE
    )
  }

  href <- ifelse(url, links, NA_character_)
  id <- ifelse(url, NA_character_, clean_nav_id(links))

  if (anyDuplicated(id, incomparables = NA)) {
    stop(
      "Each service navigation link needs a unique inputID, but these are ",
      "repeated: ",
      paste0("\"", unique(id[duplicated(id)]), "\"", collapse = ", "),
      ". inputIDs are lowercased with non-alphanumeric characters replaced ",
      "by underscores, so e.g. \"Page 1\" and \"Page-1\" both become ",
      "\"page_1\". Supply a named vector to set distinct inputIDs.",
      call. = FALSE
    )
  }

  list(id = unname(id), label = unname(label), href = unname(href))
}

#' Create a service navigation link for use in `service_navigation()` function
#'
#' @param input_id The inputID for the link, already generated by
#'   `service_nav_ids()`.
#' @param link_name The link text shown to users.
#' @param active Whether this is the current page. The active item gets the
#'   GOV.UK modifier class, `aria-current="page"`, and its text wrapped in the
#'   `govuk-service-navigation__active-fallback` `<strong>`, matching the
#'   GOV.UK markup. `service_navigation.js` moves all three on navigation.
#' @param href A URL for a link to a page outside the app, or `NA` for an
#'   in-app link. URL links are plain `<a>` elements with no inputID.
#'
#' @returns HTML tag list item
#' @noRd
#' @keywords internal
#' @examples
#' # Named internal link
#' shinyGovstyle:::service_nav_link("cookie_statement", "Cookies")
service_nav_link <- function(
  input_id,
  link_name,
  active = FALSE,
  href = NA_character_
) {
  stopifnot(!is.null(link_name), nzchar(link_name))

  if (!is.na(href)) {
    return(
      shiny::tags$li(
        class = "govuk-service-navigation__item",
        shiny::tags$a(
          class = "govuk-service-navigation__link",
          href = href,
          link_name
        )
      )
    )
  }

  shiny::tags$li(
    class = paste(
      c(
        "govuk-service-navigation__item",
        if (active) "govuk-service-navigation__item--active"
      ),
      collapse = " "
    ),
    shiny::actionLink(
      class = "govuk-service-navigation__link",
      inputId = input_id,
      label = if (active) {
        shiny::tags$strong(
          class = "govuk-service-navigation__active-fallback",
          link_name
        )
      } else {
        link_name
      },
      `aria-current` = if (active) "page"
    )
  )
}
